	return Object{"MAX_ROUNDS": 128, "OUTPUT_LANG": "Chinese", "LUADRAW_VERSION": "3.7", "ENVIRONMENT": `{"ready":true}`, "CONTEXT": "Given $x^{2}$ and 中文 labels.", "ORIGINAL_SIZE": "Original size: 100 x 120 mm", "VIEW_BUDGET": "View budget: 30 original, 25 PDF"}
