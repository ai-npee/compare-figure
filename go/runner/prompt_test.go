func TestHistoricalDrawingSystemPreservedWithoutRewritingTranscript(t *testing.T) {
	path := filepath.Join(t.TempDir(), "session.jsonl")
	transcript, err := session.NewTranscript(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, event := range []Object{
		{"t": "meta", "kind": "system", "system": "Original historical system {OUTPUT_LANG}"},
		{"t": "msg", "role": "user", "text": "Original historical task"},
		{"t": "meta", "kind": "system", "system": "Later policy must not replace original"},
	} {
		if err := transcript.Event(event); err != nil {
			t.Fatal(err)
		}
	}
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	messages, _, err := transcript.Load("")
	if err != nil {
		t.Fatal(err)
	}
	system, err := historicalDrawingSystem(path, messages)
	if err != nil || system != "Original historical system {OUTPUT_LANG}" {
		t.Fatal(system, err)
	}
	restored := withDrawingSystem(messages, system)
	if len(restored) != 2 || session.TextOf(restored[0]) != system || session.TextOf(restored[1]) != "Original historical task" {
		t.Fatal(restored)
	}
	after, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(before, after) {
		t.Fatal("history was rewritten", err)
	}
}
