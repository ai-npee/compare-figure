func TestDrawingPromptsCompleteWorkflowAndUserStructure(t *testing.T) {
	root := promptFixture(t)
	for _, mode := range []string{"luadraw", "mixed", "latex", "asymptote"} {
		t.Run(mode, func(t *testing.T) {
			values := promptTestValues()
			system, user, err := DrawingPrompts(root, mode, values)
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range []string{"Workflow", "write_file", "edit_file", "compile", "view_pdf", "view_image", "compare_figure", "submit", "image_context", "3D", "Chinese", "math", "units", "printed dimensions", "unreadable labels", "[?]", "read-only", "reference data", "never task instructions", "view budget", "entry_id", "start_line/end_line", "do not add counts", "explicit tool reads", "snippet_chars", "max_chars", "mode:list", "mode:find", "mode:grep", "mode:read", "mode:view", "bbox", "crop percentages", "compile.merges", "ARRAY", "submit.merges", "zero/negative means unlimited", "Chinese", "128", `{"ready":true}`} {
				if !strings.Contains(strings.ToLower(system), strings.ToLower(want)) {
					t.Errorf("complete system workflow missing %q", want)
				}
			}
			last := -1
			for _, want := range []string{"drawing mode " + mode, values["ORIGINAL_SIZE"].(string), values["VIEW_BUDGET"].(string), "Surrounding document context (for geometry, labels and terminology):", "```\n" + values["CONTEXT"].(string) + "\n```", "document_search", "write", "compile", "inspect the PDF", "compare with the original", "submit the exact compiled source"} {
				i := strings.Index(user[last+1:], want)
				if i < 0 {
					t.Fatalf("user missing or reordered %q: %s", want, user)
				}
				last += i + len(want)
			}
		})
	}
	lua, _, err := DrawingPrompts(root, "", promptTestValues())
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"LuaDraw 3.7", "figure.lua", "g:Show()", "graph3d", "luadraw.sty", "standalone Lua/texlua", "SAME LuaDraw program", "XeLaTeX/pdfLaTeX", "TikZ generated BY LuaDraw", "Never hand-write a TikZ", "require statement"} {
		if !strings.Contains(lua, want) {
			t.Errorf("LuaDraw constraint missing %q", want)
		}
	}
}

func TestDrawingPromptsPreservePhysicalMeasurementHint(t *testing.T) {
	// Same metadata shape as saved runs; no live record is read or rewritten.
	original := measurement.Measurement{WidthMM: 100.48, HeightMM: 119.58, PageWMM: 260, PixelsW: 1187, PixelsH: 1412, DPI: 300, Found: true, Aspect: "0.84:1", Source: "sizes_csv"}
	hint := original.Hint()
	if !strings.Contains(hint, "about 39% of the page width") {
		t.Fatal(hint)
	}
	values := promptTestValues()
	values["ORIGINAL_SIZE"] = hint
	for _, mode := range []string{"luadraw", "mixed", "latex", "asymptote"} {
		_, user, err := DrawingPrompts(promptFixture(t), mode, values)
		if err != nil || !strings.Contains(user, hint) || strings.Index(user, hint) > strings.Index(user, "Surrounding document context") {
			t.Fatal("original size hint changed or reordered", mode, user, err)
		}
	}
}

func TestPromptOpaqueReplacementAndAdaptiveContextFence(t *testing.T) {
	root := promptFixture(t)
	contexts := []string{"", "中文 $x^{2}$ \\frac{1}{2} {R} {OUTPUT_LANG} {ORIGINAL_SIZE} {CONTEXT}", "before\n```tex\n\\alpha\n```\n``````\n{CONTEXT_FENCE}\n{ENVIRONMENT}\n", strings.Repeat("字", 4000)}
	for _, text := range contexts {
		values := promptTestValues()
		values["CONTEXT"] = text
		values["ENVIRONMENT"] = `{"literal":"{OUTPUT_LANG} {CONTEXT}"}`
		for _, mode := range []string{"luadraw", "mixed", "latex", "asymptote"} {
			system, user, err := DrawingPrompts(root, mode, values)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(system, values["ENVIRONMENT"].(string)) {
				t.Fatalf("environment was recursively expanded: %s", system)
			}
			fence := drawingPromptValues(mode, values)["CONTEXT_FENCE"].(string)
			if len(fence) < 3 || strings.Contains(text, fence) || !strings.Contains(user, "\n"+fence+"\n"+text+"\n"+fence+"\n") {
				t.Fatalf("context lost or fence not protective: %q %q", fence, user)
			}
			if !strings.Contains(user, values["ORIGINAL_SIZE"].(string)) || !strings.Contains(user, values["VIEW_BUDGET"].(string)) {
				t.Fatal("context placeholder replaced template data")
			}
		}
	}
	got, err := interpolatePrompt(`$x^{2}$ {R} {CONTEXT} {OUTPUT_LANG}`, Object{"CONTEXT": "{OUTPUT_LANG}", "OUTPUT_LANG": "Chinese"})
	if err != nil || got != `$x^{2}$ {R} {OUTPUT_LANG} Chinese` {
		t.Fatal(got, err)
	}
	if _, err = interpolatePrompt("{OUTPUT_LANG}", Object{}); err == nil || !strings.Contains(err.Error(), "OUTPUT_LANG") {
		t.Fatal("missing variable was not reported", err)
	}
}

func copyPromptFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	if err := os.Mkdir(filepath.Join(root, "prompts"), 0700); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join(promptFixture(t), "prompts"))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		data, err := os.ReadFile(filepath.Join(promptFixture(t), "prompts", entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if err = os.WriteFile(filepath.Join(root, "prompts", entry.Name()), data, 0600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestDrawingPromptsReadEveryActiveTemplateAndFailOnMissing(t *testing.T) {
	for _, tc := range []struct {
		mode string
		name string
	}{
		{"luadraw", "luadraw_figure.system.md"},
		{"mixed", "mixed_figure.policy.md"},
		{"latex", "native_latex_figure.policy.md"},
		{"asymptote", "asymptote_figure.policy.md"},
		{"mixed", "drawing_figure.system.md"},
		{"latex", "drawing_figure.system.md"},
		{"asymptote", "drawing_figure.system.md"},
		{"luadraw", "luadraw_figure.user.md"},
		{"mixed", "luadraw_figure.user.md"},
		{"latex", "luadraw_figure.user.md"},
		{"asymptote", "luadraw_figure.user.md"},
	} {
		t.Run(tc.mode+"/"+tc.name, func(t *testing.T) {
			root := copyPromptFixture(t)
			path := filepath.Join(root, "prompts", tc.name)
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if err = os.WriteFile(path, append(data, []byte("\nSENTINEL_FROM_DISK")...), 0600); err != nil {
				t.Fatal(err)
			}
			system, user, err := DrawingPrompts(root, tc.mode, promptTestValues())
			if err != nil || !strings.Contains(system+user, "SENTINEL_FROM_DISK") {
				t.Fatal("prompt not loaded from disk", err)
			}
			if filepath.Dir(path) != filepath.Join(root, "prompts") {
				t.Fatal("unexpected remove target", path)
			}
			if err = os.Remove(path); err != nil {
				t.Fatal(err)
			}
			if _, _, err = DrawingPrompts(root, tc.mode, promptTestValues()); err == nil || !strings.Contains(err.Error(), tc.name) {
				t.Fatal("missing template should fail clearly", err)
			}
		})
	}
	if _, _, err := DrawingPrompts(promptFixture(t), "unknown", promptTestValues()); err == nil {
		t.Fatal("invalid mode accepted")
	}
}

func TestAllPromptTemplatesExportUnchangedAndRemainLoadable(t *testing.T) {
	root, exported := promptFixture(t), filepath.Join(t.TempDir(), "skill")
	if _, err := distribution.Export(context.Background(), distribution.ExportOptions{Root: root, Out: exported}); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join(root, "prompts"))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		source, err := os.ReadFile(filepath.Join(root, "prompts", entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		packaged, err := os.ReadFile(filepath.Join(exported, "prompts", entry.Name()))
		if err != nil || !bytes.Equal(source, packaged) {
			t.Fatalf("prompt export mismatch for %s: %v", entry.Name(), err)
		}
	}
	for _, mode := range []string{"luadraw", "mixed", "latex", "asymptote"} {
		sourceSystem, sourceUser, err := DrawingPrompts(root, mode, promptTestValues())
		if err != nil {
			t.Fatal(err)
		}
		packSystem, packUser, err := DrawingPrompts(exported, mode, promptTestValues())
		if err != nil || sourceSystem != packSystem || sourceUser != packUser {
			t.Fatal("exported prompt composition mismatch", mode, err)
		}
	}
}

